"""Set up ligand-bound ternary complex MD simulation.

Combines the equilibrated ternary system (gp120+CD4+CCR5) with
BMS-626529 (GAFF2/AM1-BCC parameterization from acpype) and
generates all input files for EM -> NVT -> NPT -> Production MD.
"""
import subprocess, os, sys, shutil

WORKDIR = os.path.join(DATA_ROOT, "results", "04-md-simulations")
TOPOLOGY_DIR = os.path.join(WORKDIR, 'topology')
ACPYPE_DIR = os.path.join(WORKDIR, 'jyv_clean.acpype')
TERNARY_GRO = os.path.join(DATA_ROOT, "topology", "md.gro")
LIGAND_PDB = os.path.join(DATA_ROOT, "docking/bms626529_positioned.pdb")

os.chdir(WORKDIR)

def run(cmd, check=True):
    print(f'>>> {cmd}')
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    if r.stdout: print(r.stdout[:2000])
    if r.stderr: print(r.stderr[:2000])
    if check and r.returncode != 0:
        raise RuntimeError(f'Command failed: {cmd}')
    return r

# Step 1: Extract ligand ITP from parmed-generated top
print('=== Step 1: Extract ligand ITP ===')
with open(os.path.join(ACPYPE_DIR, 'jyv_clean_GMX.top')) as f:
    top_content = f.read()

lines = top_content.split('\n')
in_atomtypes = False
in_moleculetype = False
atomtypes_lines = []
itp_lines = []

for line in lines:
    stripped = line.strip()
    if stripped.startswith('[ defaults ]'):
        continue
    if stripped.startswith('[ atomtypes ]'):
        in_atomtypes = True
        atomtypes_lines.append(line)
        continue
    if stripped.startswith('[ moleculetype ]'):
        in_atomtypes = False
        in_moleculetype = True
        itp_lines.append(line)
        continue
    if stripped.startswith('[ system ]') or stripped.startswith('[ molecules ]'):
        in_moleculetype = False
        continue
    if in_atomtypes:
        atomtypes_lines.append(line)
    elif in_moleculetype:
        itp_lines.append(line)

with open(os.path.join(WORKDIR, 'UNL_atomtypes.itp'), 'w') as f:
    f.write('; BMS-626529 (UNL) atom types - GAFF2\n')
    f.write('\n'.join(atomtypes_lines))
    f.write('\n')
print(f'  Wrote UNL_atomtypes.itp ({len(atomtypes_lines)} lines)')

with open(os.path.join(WORKDIR, 'UNL.itp'), 'w') as f:
    f.write('; BMS-626529 (UNL) topology - GAFF2 with AM1-BCC charges\n')
    f.write('; Generated by acpype + parmed\n\n')
    f.write('\n'.join(itp_lines))
    f.write('\n')
print(f'  Wrote UNL.itp ({len(itp_lines)} lines)')

# Step 2: Convert ligand PDB to GRO
print('\n=== Step 2: Convert ligand PDB to GRO ===')
run(f'gmx editconf -f {LIGAND_PDB} -o ligand.gro')

# Step 3: Copy ternary equilibrated structure
print('\n=== Step 3: Copy ternary structure ===')
shutil.copy(TERNARY_GRO, os.path.join(WORKDIR, 'ternary.gro'))

# Step 4: Combine protein+ligand, remove overlapping waters
print('\n=== Step 4: Insert ligand and remove overlapping waters ===')
with open('ternary.gro') as f:
    ternary_lines = f.readlines()

with open('ligand.gro') as f:
    ligand_lines = f.readlines()

title = ternary_lines[0].strip()
n_ternary = int(ternary_lines[1].strip())
box_line = ternary_lines[-1]

ternary_atoms = ternary_lines[2:-1]
ligand_atoms = ligand_lines[2:-1]

ligand_positions = []
for line in ligand_atoms:
    x = float(line[20:28])
    y = float(line[28:36])
    z = float(line[36:44])
    ligand_positions.append((x, y, z))

OVERLAP_DIST = 0.2  # nm
filtered_atoms = []
removed_waters = 0
i = 0
while i < len(ternary_atoms):
    line = ternary_atoms[i]
    resname = line[5:10].strip()
    if resname == 'SOL':
        try:
            x = float(line[20:28])
            y = float(line[28:36])
            z = float(line[36:44])
        except (ValueError, IndexError):
            filtered_atoms.append(line)
            i += 1
            continue

        overlaps = False
        for lx, ly, lz in ligand_positions:
            d2 = (x-lx)**2 + (y-ly)**2 + (z-lz)**2
            if d2 < OVERLAP_DIST**2:
                overlaps = True
                break

        if overlaps:
            removed_waters += 1
            i += 3
            continue
        else:
            filtered_atoms.append(line)
            i += 1
    else:
        filtered_atoms.append(line)
        i += 1

print(f'  Removed {removed_waters} overlapping water molecules ({removed_waters*3} atoms)')

water_start = None
for idx, line in enumerate(filtered_atoms):
    resname = line[5:10].strip()
    if resname == 'SOL':
        water_start = idx
        break

if water_start is None:
    water_start = len(filtered_atoms)

combined = filtered_atoms[:water_start] + ligand_atoms + filtered_atoms[water_start:]
n_total = len(combined)

with open('combined.gro', 'w') as f:
    f.write(f'{title} + BMS-626529\n')
    f.write(f'{n_total}\n')
    for line in combined:
        f.write(line if line.endswith('\n') else line + '\n')
    f.write(box_line)

print(f'  Combined system: {n_total} atoms (was {n_ternary})')

# Step 5: Create modified topology
print('\n=== Step 5: Create combined topology ===')
with open(os.path.join(TOPOLOGY_DIR, 'topol.top')) as f:
    top_lines = f.readlines()

new_top = []
for line in top_lines:
    if '#include "amber99sb-ildn.ff/forcefield.itp"' in line:
        new_top.append(line)
        new_top.append('\n; Include BMS-626529 ligand atom types\n')
        new_top.append('#include "UNL_atomtypes.itp"\n')
        continue
    if '#include "topol_Protein_chain_C.itp"' in line:
        new_top.append(line.replace('#include "', '#include "topology/'))
        new_top.append('\n; Include BMS-626529 ligand topology\n')
        new_top.append('#include "UNL.itp"\n')
        continue
    if '#include "topol_Protein_chain_' in line or '#include "posre_Protein_chain_' in line:
        new_top.append(line.replace('#include "', '#include "topology/'))
        continue
    if line.startswith('SOL'):
        sol_count = 92689 - removed_waters
        new_top.append(f'SOL         {sol_count}\n')
        continue
    new_top.append(line)

final_top = []
for line in new_top:
    if line.startswith('SOL'):
        final_top.append('UNL                 1\n')
    final_top.append(line)

with open('topol.top', 'w') as f:
    f.writelines(final_top)

print('  Wrote combined topol.top')

# Step 6: Create MDP files
print('\n=== Step 6: Create MDP files ===')
mdp_dir = os.path.join(WORKDIR, 'mdp')
os.makedirs(mdp_dir, exist_ok=True)

em_mdp = """; Energy minimization
integrator  = steep
emtol       = 1000.0
emstep      = 0.01
nsteps      = 50000
nstlist     = 10
cutoff-scheme = Verlet
ns_type     = grid
coulombtype = PME
rcoulomb    = 1.0
rvdw        = 1.0
pbc         = xyz
"""

nvt_mdp = """; NVT equilibration (100 ps)
integrator  = md
nsteps      = 50000
dt          = 0.002
nstxout     = 5000
nstvout     = 5000
nstenergy   = 5000
nstlog      = 5000
continuation = no
gen_vel     = yes
gen_temp    = 300
gen_seed    = -1
constraint_algorithm = lincs
constraints = h-bonds
lincs_iter  = 1
lincs_order = 4
cutoff-scheme = Verlet
ns_type     = grid
nstlist     = 10
rcoulomb    = 1.0
rvdw        = 1.0
coulombtype = PME
pme_order   = 4
fourierspacing = 0.16
tcoupl      = V-rescale
tc-grps     = Protein Non-Protein
tau_t       = 0.1   0.1
ref_t       = 300   300
pcoupl      = no
pbc         = xyz
DispCorr    = EnerPres
define      = -DPOSRES
"""

npt_mdp = """; NPT equilibration (100 ps)
integrator  = md
nsteps      = 50000
dt          = 0.002
nstxout     = 5000
nstvout     = 5000
nstenergy   = 5000
nstlog      = 5000
continuation = yes
gen_vel     = no
constraint_algorithm = lincs
constraints = h-bonds
lincs_iter  = 1
lincs_order = 4
cutoff-scheme = Verlet
ns_type     = grid
nstlist     = 10
rcoulomb    = 1.0
rvdw        = 1.0
coulombtype = PME
pme_order   = 4
fourierspacing = 0.16
tcoupl      = V-rescale
tc-grps     = Protein Non-Protein
tau_t       = 0.1   0.1
ref_t       = 300   300
pcoupl      = Parrinello-Rahman
pcoupltype  = isotropic
tau_p       = 2.0
ref_p       = 1.0
compressibility = 4.5e-5
refcoord_scaling = com
pbc         = xyz
DispCorr    = EnerPres
define      = -DPOSRES
"""

md_mdp = """; Production MD (10 ns)
integrator  = md
nsteps      = 5000000
dt          = 0.002
nstxout-compressed = 5000
compressed-x-grps  = System
nstenergy   = 5000
nstlog      = 5000
continuation = yes
gen_vel     = no
constraint_algorithm = lincs
constraints = h-bonds
lincs_iter  = 1
lincs_order = 4
cutoff-scheme = Verlet
ns_type     = grid
nstlist     = 10
rcoulomb    = 1.0
rvdw        = 1.0
coulombtype = PME
pme_order   = 4
fourierspacing = 0.16
tcoupl      = V-rescale
tc-grps     = Protein Non-Protein
tau_t       = 0.1   0.1
ref_t       = 300   300
pcoupl      = Parrinello-Rahman
pcoupltype  = isotropic
tau_p       = 2.0
ref_p       = 1.0
compressibility = 4.5e-5
pbc         = xyz
DispCorr    = EnerPres
"""

for name, content in [('em.mdp', em_mdp), ('nvt.mdp', nvt_mdp), ('npt.mdp', npt_mdp), ('md.mdp', md_mdp)]:
    with open(os.path.join(mdp_dir, name), 'w') as f:
        f.write(content)
    print(f'  Wrote {name}')

print('\n=== Setup complete ===')
print(f'Working directory: {WORKDIR}')
print('Next: run run_ligand_md.sh')
